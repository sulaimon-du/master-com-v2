// Copies vendored JS and self-hosted fonts into app/static. Runs at build time; no CDN at runtime (CSP: 'self' only).
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const nm = (...p) => join(root, "node_modules", ...p);
const out = (...p) => join(root, "app", "static", ...p);

mkdirSync(out("js"), { recursive: true });
mkdirSync(out("fonts"), { recursive: true });
mkdirSync(out("css"), { recursive: true });

copyFileSync(nm("htmx.org", "dist", "htmx.min.js"), out("js", "htmx.min.js"));
// Alpine CSP build: no eval/new Function, so the page CSP can stay strict (script-src 'self').
copyFileSync(nm("@alpinejs", "csp", "dist", "cdn.min.js"), out("js", "alpine-csp.min.js"));

// Subsets we need: cyrillic-ext carries the Tajik letters ғ ӣ қ ӯ ҳ ҷ.
const SUBSETS = ["cyrillic-ext", "cyrillic", "latin-ext", "latin"];
const sources = [
  [nm("@fontsource-variable", "inter"), "wght.css"],
  [nm("@fontsource", "cormorant-garamond"), "600.css"],
  [nm("@fontsource", "cormorant-garamond"), "700.css"],
];

let css = "/* Generated by scripts/vendor.mjs from @fontsource packages. Do not edit. */\n";
for (const [dir, file] of sources) {
  const text = readFileSync(join(dir, file), "utf8");
  for (const block of text.split("/*").slice(1)) {
    const header = block.slice(0, block.indexOf("*/"));
    if (!SUBSETS.some((s) => header.includes(`-${s}-`))) continue;
    const face = block.slice(block.indexOf("@font-face"));
    css += face.replace(/url\(\.\/files\/([^)]+)\)/g, (_, f) => {
      copyFileSync(join(dir, "files", f), out("fonts", f));
      return `url(/static/fonts/${f})`;
    }).trim() + "\n";
  }
}
writeFileSync(out("css", "fonts.css"), css);
console.log("vendor: js and fonts copied");
